"""PeerShop protocol: the message schema two personal agents use to trade.

Every personal agent imports this exact file. uAgents hashes the models and the
spec into a protocol digest; two agents can only exchange these messages if the
digests match, so do not edit this file on one teammate's machine only.
"""

from uagents import Model
from uagents_core.protocol import ProtocolSpecification


class WantToBuy(Model):
    """Buyer agent -> every peer agent. The buyer's cap is never sent."""
    intent_id: str
    query: str                 # "stagg kettle"
    opening_bid_cents: int     # buyer's first number (60% of the private cap)
    buyer_name: str


class Offer(Model):
    """Seller agent -> buyer agent. round 0 = list price."""
    intent_id: str
    item_id: str
    title: str
    condition: str
    list_price_cents: int
    price_cents: int
    round: int
    final: bool = False        # seller has reached its floor or its last round


class Counter(Model):
    """Buyer agent -> seller agent."""
    intent_id: str
    item_id: str
    price_cents: int
    round: int


class Hold(Model):
    """Buyer agent -> seller agent: offer is acceptable, waiting on the other
    sellers and on the buyer's own approval (ASI:One review card)."""
    intent_id: str
    item_id: str
    reason: str


class Accept(Model):
    """Buyer agent -> winning seller agent, sent only after the human approved.
    The seller answers with RequestPayment (AgentPaymentProtocol)."""
    intent_id: str
    item_id: str
    price_cents: int


class NoDeal(Model):
    """Either side ends the negotiation."""
    intent_id: str
    reason: str


shop_spec = ProtocolSpecification(
    name="PeerShopProtocol",
    version="0.1.0",
    interactions={
        WantToBuy: {Offer, NoDeal},
        Offer: {Counter, Hold, NoDeal},
        Counter: {Offer, NoDeal},
        Hold: set(),
        Accept: set(),          # reply travels on the payment protocol
        NoDeal: set(),
    },
)
