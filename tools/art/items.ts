// Item icons: 16x16, drawn as <=14x14 grids that are centred and given an ink outline.
// One shared legend — .=clear  W=white  c=cream  p=path  y=gold  s=sky  l=lav  n=pink  r=red  m=mint  k=ink  g=grass  e=peach
import { blank, blitOutlined, grid, type Img, type Legend } from "./lib";

const L: Legend = {
  W: "white", c: "cream", p: "path", y: "gold", s: "sky", l: "lav", n: "pink", r: "red", m: "mint", k: "ink", g: "grass", e: "peach",
};

function icon(name: string, rows: string[]): { name: string; img: Img } {
  const g = grid(rows, L, name);
  if (g.w > 14 || g.h > 14) throw new Error(`${name}: ${g.w}x${g.h} exceeds 14x14`);
  const img = blank(16, 16);
  blitOutlined(img, g, Math.floor((16 - g.w) / 2), Math.floor((16 - g.h) / 2));
  return { name, img };
}

